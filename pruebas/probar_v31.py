"""Prueba funcional de la maqueta CON012 v4 con Playwright (Chromium, sin red)."""
import pathlib, sys
from playwright.sync_api import sync_playwright

RAIZ = pathlib.Path(__file__).resolve().parent.parent
URL = (RAIZ / "index.html").as_uri()
CAPT = RAIZ / "pruebas" / "capturas"
CAPT.mkdir(parents=True, exist_ok=True)
fallos, errores = [], []

def check(cond, msg):
    print(("OK   " if cond else "FALLA") + " " + msg)
    if not cond:
        fallos.append(msg)

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1280, "height": 900})
    pg.on("console", lambda m: m.type == "error" and errores.append(m.text))
    pg.on("pageerror", lambda e: errores.append(str(e)))
    pg.on("dialog", lambda d: d.accept("Nota de prueba"))
    pg.goto(URL)

    # 1-2. identificación con Clave Única (simulada); representante exige poder notarial
    pg.click("nav button[data-v='v-ident']")
    pg.click("#btnCU")
    pg.wait_for_timeout(900)
    check(pg.is_visible("#cuOk") and "Clave Única" in pg.inner_text("#idMetodo"), "identificación con Clave Única")
    pg.select_option("#rol", "rep")
    check("notarial" in pg.inner_text("#lblRepDoc"), "representante: se pide poder notarial")
    pg.fill("#repRun", "1-9');window.__xss=1;('")
    pg.fill("#repNombre", "<img src=x onerror=window.__xss2=1>")
    pg.click("section#v-ident button[onclick*='muestraPaso(2)']")

    # 3. formulario: detalle obligatorio, poder notarial y correo
    pg.click(".derecho[data-d='acceso']")
    pg.click("#btnSig"); pg.click("#btnSig")
    pg.check("#decl")
    pg.click("#btnEnviar")
    e = pg.inner_text("#errForm")
    check("campos obligatorios (*) de Acceso" in e, "detalle obligatorio en el derecho")
    check("poder notarial" in e, "exige adjuntar el poder notarial")
    pg.click("#btnAnt"); pg.click("#btnAnt")
    pg.fill("#bd-acceso textarea", "Antecedentes como ex funcionaria, Región del Maule, 2015-2020")
    pg.set_input_files("#repDoc", str(RAIZ / "pruebas" / "cedula_ficticia.png"))
    check(pg.locator("#ofi option:has-text('Provincial')").count() == 0 and pg.locator("#ofi option").count() == 17, "retiro solo en Oficinas de Partes (Central + 16 regionales)")
    pg.click("#btnSig"); pg.click("#btnSig")
    pg.click("#btnEnviar")
    check("Indique un correo" in pg.inner_text("#errForm"), "exige correo cuando el medio es correo (en la misma vista)")
    pg.click("#btnAnt")
    pg.fill("#correo", "persona@correo.cl")
    pg.click("#btnSig")
    pg.click("#btnEnviar")
    pg.wait_for_timeout(1000)
    check(pg.is_visible("#v-acuse"), "envío lleva al acuse")
    num = pg.inner_text("#acNum")
    check(num.startswith("DP-2026-"), f"número de caso {num}")
    check(pg.inner_text("#acFecha").startswith("20-10-2026"), "fecha simulada 20-10-2026")

    # 5. recorrido completo por perfiles
    pg.click("nav button[data-v='v-bandeja']")
    def perfil(v): pg.evaluate(f"cambiaPerfil('{v}');muestraSub('tareas')")
    def accion(code):
        pg.click(f"#detalle button[onclick*=\"'{code}'\"]")
    def abrir(n): pg.evaluate(f"ver('{n}')")
    perfil("jefatura"); abrir(num); accion("verif")
    pg.click("#detalle a[data-caso]")
    check(pg.evaluate("window.__xss===undefined && window.__xss2===undefined"), "RUN y nombre del solicitante no ejecutan código")
    perfil("fiscalia"); abrir(num); accion("adm")
    perfil("jefatura"); abrir(num); accion("derivar")
    perfil("gerencia"); abrir(num); accion("acoge")
    perfil("fiscalia"); abrir(num); accion("conforme")
    perfil("jefatura"); abrir(num); accion("firma")
    perfil("jefatura"); abrir(num)
    pg.click("#detalle button:has-text('Nota interna')")
    pg.fill("#txtNota", "Nota de prueba")
    pg.click("text=Guardar nota")
    check("Nota de prueba" in pg.inner_text("#detalle"), "nota interna queda en el expediente")
    accion("enviar")
    check("Respondida" in pg.inner_text("#detalle"), "caso nuevo termina en Respondida")

    # sub-flujo de reclamo ante la Agencia sobre el caso 000116 (rechazado)
    perfil("jefatura"); abrir("DP-2026-000116")
    pg.click("#detalle button:has-text('Registrar reclamo de la Agencia')")
    check("Reclamada ante la Agencia" in pg.inner_text("#detalle"), "reclamo registrado")
    perfil("fiscalia"); abrir("DP-2026-000116"); accion("informe")
    check("Respondida" in pg.inner_text("#detalle"), "informe a la Agencia cierra el reclamo")

    # sin verificación por correo; quien no tiene Clave Única va a Oficina de Partes
    pg.goto(URL)
    pg.click("nav button[data-v='v-ident']")
    check(pg.locator("#detCorreo").count() == 0 and pg.locator("#altCedula").count() == 0, "no existe la verificación por correo ni por copia en el formulario web")
    check("Oficina de Partes" in pg.inner_text("#porQueId"), "indica Oficina de Partes a quien no tenga Clave Única")
    # plazo para aportar antecedentes: caso 000121 vence hoy → Fiscalía puede denegar
    pg.click("nav button[data-v='v-bandeja']")
    perfil("fiscalia"); abrir("DP-2026-000121")
    check("plazo para aportarlos: 20-10-2026" in pg.inner_text("#detalle"), "muestra el plazo para aportar antecedentes")
    accion("denant")
    check("En firma" in pg.inner_text("#detalle") and "reclamar ante la Agencia" in pg.inner_text("#detalle"), "denegación por falta de antecedentes con aviso de reclamo")
    perfil("jefatura"); abrir("DP-2026-000122")
    pg.evaluate("ir('v-info')")
    check(pg.locator("#v-info .pd-grid").is_visible(), "página general de protección de datos")
    pd = pg.inner_text("#v-info")
    tit = pg.evaluate("[...document.querySelectorAll('#v-info .pd-item h3')].map(h=>h.textContent.trim())")
    check(tit == [f"{n}" + t for n, t in [(1,"Formulario de solicitudes"),(2,"Política de protección de datos personales"),(3,"Delegado de protección de datos"),(4,"Matriz de datos personales"),(5,"Responsable y representante legal"),(6,"Domicilio y canales para solicitudes"),(7,"Política y medidas de seguridad"),(8,"Derechos y reclamo ante la Agencia"),(9,"Categorías, destinatarios y finalidades"),(10,"Conservación, fuente y transferencias"),(11,"Decisiones automatizadas")]], f"página PD con las 11 secciones en orden: {tit}")
    pg.click("nav button[data-v='v-bandeja']")
    pg.evaluate("abreRegistro('carta',true)")
    pg.select_option("#rmIdent", "pend")
    pg.click("text=Registrar y enviar acuse")
    check("Requiere antecedentes" in pg.inner_text("#detalle") and "copia de su cédula" in pg.inner_text("#detalle"), "registro manual sin cédula queda en Requiere antecedentes")

    # vías de ingreso: registro manual por el encargado
    pg.goto(URL)
    pg.click("nav button[data-v='v-bandeja']")
    perfil("fiscalia")
    check(pg.locator("#barraRegistro").is_hidden(), "fiscalía no ve el botón de registro manual")
    perfil("jefatura")
    check(pg.locator("#barraRegistro").is_visible(), "jefatura ve el botón de registro manual")
    pg.click("#barraRegistro button")
    pg.click("text=Registrar y enviar acuse")
    e = pg.inner_text("#errRm")
    check("vía de ingreso" in e and "documento original" in e, "registro manual valida campos obligatorios")
    pg.select_option("#rmVia", "carta")
    pg.fill("#rmFecha", "2026-10-25")
    pg.click("text=Registrar y enviar acuse")
    check("posterior a hoy" in pg.inner_text("#errRm"), "rechaza fecha de ingreso futura")
    check("timbre" in pg.inner_text("#lblRmFecha"), "etiqueta de fecha según la vía (carta)")
    pg.click("text=Cargar ejemplo")
    pg.fill("#rmFolio", "<img src=x onerror=window.__xss3=1>")
    pg.click("text=Registrar y enviar acuse")
    det = pg.inner_text("#detalle")
    check("Formulario físico en Oficina de Partes" in det, "caso registrado con su vía")
    venc = pg.evaluate("fmt(CASOS[0].venc)"); ing = pg.evaluate("fmt(CASOS[0].ingreso)")
    check(ing == "16-10-2026" and venc == "15-11-2026", f"plazo desde la fecha de ingreso ({ing} → {venc})")
    check("se registró 4 día(s) después" in det, "muestra el desfase entre ingreso y registro")
    check(pg.evaluate("window.__xss3===undefined"), "folio con código no se ejecuta")
    pg.evaluate("document.getElementById('todosCasos').open=true")
    check("Oficina de Partes" in pg.inner_text("#tr-" + pg.evaluate("CASOS[0].num")), "columna Vía en la bandeja")
    ncartas = pg.evaluate("CASOS.filter(c=>c.via==='carta').length")
    pg.select_option("#fVia", "carta")
    check(pg.locator("#tbody tr").count() == ncartas, f"filtro por vía ({ncartas} cartas)")
    pg.select_option("#fVia", "")
    # pestaña 8
    pg.click("nav button[data-v='v-vias']")
    check(f"{ncartas} casos en la bandeja" in pg.inner_text("#cnt-carta"), "contador por vía se actualiza")

    # 8. definiciones de Fiscalía cambian el canal
    pg.evaluate("cambiaCFG('supr','no')")
    pg.evaluate("cambiaCFG('adm','jefatura')")
    pg.evaluate("cambiaCFG('ia','si')")
    pg.evaluate("cambiaCFG('firma','delegada')")
    check("Unidad receptora" in pg.inner_text("#hAdmT"), "flujo: admisibilidad pasa a la jefatura")
    check("delegada" in pg.inner_text("#hFirD"), "flujo: firma delegada")
    check("supresión" not in pg.inner_text("#infoTitular"), "info al titular ya no ofrece supresión")
    check(pg.locator(".derecho[data-d='supr']").is_hidden(), "tarjeta de supresión oculta")
    check(pg.locator("nav button[data-v='v-fiscalia']").count() == 0 and pg.locator("#v-fiscalia").count() == 0, "pestaña de Fiscalía retirada")
    check("Requisitos para la versión institucional" in pg.inner_text("#v-flujo"), "requisitos trasladados a Flujo y plazos")
    pg.click("nav button[data-v='v-bandeja']")
    perfil("gerencia")
    pg.click("#listaTareas .tarea >> nth=0 >> button")
    check("Borrador sugerido" not in pg.inner_text("#detalle"), "sin borrador de IA en la gestión")
    perfil("jefatura"); abrir("DP-2026-000123")
    check(pg.locator("#detalle button[onclick*=\"'adm'\"]").count() == 1, "con la opción 'jefatura', ésta ve la acción de admisibilidad")
    pg.click("nav button[data-v='v-bandeja']")
    pg.click("#subParametros")
    check("no ofrecido" in pg.inner_text("#vistaParametros"), "parámetros reflejan supresión no ofrecida")

    # tablero de control y mis tareas
    pg.goto(URL)
    pg.click("nav button[data-v='v-bandeja']")
    check(pg.is_visible("#vistaTareas") and pg.is_hidden("#vistaTablero"), "la pestaña 5 abre en Mis tareas")
    tab = pg.inner_text("#vistaTablero")
    for frag in ["Casos abiertos", "Respondidos dentro de plazo", "Riesgo de vencimiento", "Por vía de ingreso"]:
        check(frag.lower() in tab.lower(), f"tablero muestra «{frag}»")
    check("NaN" not in tab and "undefined" not in tab, "tablero sin valores inválidos")
    nombres = pg.evaluate("CASOS.slice(0,5).map(c=>c.nombre)")
    check(all(n not in tab for n in nombres), "tablero no muestra nombres de titulares")
    ab = pg.evaluate("CASOS.filter(c=>!c.cerrado).length")
    check(pg.inner_text(".kpi-t .v >> nth=0").strip() == str(ab), f"KPI de casos abiertos coincide con los datos ({ab})")
    pg.click("#subTareas")
    check(pg.is_visible("#listaTareas"), "subvista Mis tareas")
    for p in ["jefatura", "fiscalia", "gerencia"]:
        perfil(p)
        n = pg.locator("#listaTareas .tarea").count()
        esperado = pg.evaluate(f"CASOS.filter(c=>tareaDe(c,'{p}')).length")
        check(n == esperado, f"{p}: {n} tareas")
    perfil("fiscalia")
    check("bloqueo temporal" in pg.inner_text("#listaTareas .tarea >> nth=0").lower(), "Fiscalía ve primero el bloqueo pendiente")
    pg.click("#listaTareas .tarea >> nth=0 >> button")
    check("DP-2026-000123" in pg.inner_text("#detalle"), "abrir tarea muestra el expediente")
    pg.click("#subTablero")
    pg.click("#vistaTablero .riesgo .r >> nth=0 >> button")
    check(pg.is_visible("#vistaTareas") and pg.inner_text("#detalle").startswith("DP-"), "abrir desde el tablero lleva al expediente")

    # capturas y desborde horizontal por vista, en escritorio y teléfono
    for ancho, alto, et in [(1280, 900, "escritorio"), (375, 812, "telefono")]:
        pg.set_viewport_size({"width": ancho, "height": alto})
        for v in ["v-sitio", "v-ident", "v-form", "v-acuse", "v-bandeja", "v-caso", "v-flujo", "v-perfiles", "v-vias"]:
            pg.evaluate(f"ir('{v}')")
            if v == "v-bandeja":
                pg.evaluate("cambiaPerfil('jefatura');muestraSub('tablero')")
            pg.wait_for_timeout(150)
            desb = pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
            check(desb <= 1, f"{et} {v}: sin desplazamiento horizontal de la página ({desb}px)")
            pg.screenshot(path=str(CAPT / f"{et}_{v}.png"), full_page=True)
    b.close()

check(not errores, "sin errores de consola: " + "; ".join(errores[:3]))
print(f"\n{len(fallos)} fallas")
sys.exit(1 if fallos else 0)
